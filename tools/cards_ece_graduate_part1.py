def write(all_cards):
    ids = [c["id"] for c in all_cards]
    assert len(ids) == len(set(ids)), "duplicate card id"
    assert all(1 <= len(c["rule"]) <= 5 for c in all_cards), "rule must be 1 to 5 lines"
    assert all(len(c["title"].split()) <= 10 for c in all_cards), "title too long"
    out = Path(__file__).resolve().parent.parent / "data" / "ECE" / "cards.json"
    out.write_text(json.dumps(all_cards, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{len(all_cards)} cards written to data/ECE/cards.json")
